#!/usr/bin/env python3
"""Convert tools/font6.txt (ASCII art) into src/font6.asm."""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "font6.txt")
dst = os.path.join(here, "..", "src", "font6.asm")
glyphs, cur = {}, None
for line in open(src):
    line = line.rstrip("\n")
    if not line or line.startswith("#") and not set(line) <= set("#."):
        continue
    if line.startswith(": "):
        ch = line[2:]
        cur = " " if ch == "SP" else ch
        glyphs[cur] = []
    else:
        glyphs[cur].append(line)
out = ["; Generated by tools/mkfont.py from tools/font6.txt - do not edit.",
       "; Proportional font, chars 32-126: width table (incl. 1 px spacing)",
       "; and 8 bytes per glyph, left aligned (bit 7 = leftmost pixel).", "", "font6_w:"]
widths, data = [], []
for c in range(32, 127):
    rows = glyphs.get(chr(c))
    if rows is None:
        sys.exit("missing glyph %r" % chr(c))
    w = len(rows[0])
    assert all(len(r) == w for r in rows) and len(rows) in (6, 7) and w <= 5, chr(c)
    lines = [0] + [int(r.replace("#", "1").replace(".", "0").ljust(8, "0"), 2) for r in rows]
    lines += [0] * (8 - len(lines))
    widths.append(w + 1)
    data.append((chr(c), lines))
for i in range(0, len(widths), 16):
    out.append("        db " + ",".join(str(w) for w in widths[i:i + 16]))
out.append("font6_g:")
for ch, lines in data:
    out.append("        db " + ",".join("0x%02X" % b for b in lines) + "   ; " + repr(ch))
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, len(data), "glyphs")
